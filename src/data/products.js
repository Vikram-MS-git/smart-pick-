export const allProducts = [...laptops, ...mobiles, ...earphones];

export const getProductsByCategory = (category) => {
  switch (category) {
    case "Laptop":
      return laptops;
    case "Mobile":
      return mobiles;
    case "Earphones":
      return earphones;
    default:
      return allProducts;
  }
};

export const getProductById = (id) => allProducts.find((p) => p.id === id);
